import { launchBrowser, startApp, openTool, sleep } from '../helpers/harness.mjs';
const b = await launchBrowser(); const app = await startApp();
const env = await openTool(b, app, { initScripts: [`if (window !== window.top) window.fetch = () => Promise.resolve(new Response('simulated'));`] });
await sleep(4000);
console.log(process.env.OFFLINESEAL_BROWSER || 'chromium', 'shell state:', await env.page.getAttribute('body', 'data-state'), '| fatal:', await env.page.textContent('#fatal-text'));
const fr = env.page.frames()[1];
if (fr) console.log('frame state:', await fr.evaluate(() => document.body.dataset.state).catch(e => e.message.slice(0, 80)));
console.log(env.consoleMessages.filter(m => !/Refused|violates|Fetch API/.test(m.text)).map(m => m.type + ': ' + m.text.slice(0, 160)).join('\n'));
console.log('pageErrors', env.pageErrors);
await b.close(); await app.close();
